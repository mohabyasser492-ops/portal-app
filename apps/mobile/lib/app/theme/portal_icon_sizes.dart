/// Defines the icon-size scale used throughout Portal App.
///
/// These values control the visual size of icons. Interactive icons must still
/// be placed inside controls with sufficiently large touch targets.
final class PortalIconSizes {
  const PortalIconSizes._();

  static const double xs = 12;
  static const double sm = 16;
  static const double md = 20;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 40;
  static const double display = 48;
}
