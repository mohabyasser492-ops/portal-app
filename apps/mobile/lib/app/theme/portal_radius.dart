/// Defines the corner-radius scale used throughout Portal App.
///
/// Widgets should use these tokens instead of arbitrary radius values.
/// This keeps buttons, cards, inputs, badges, and dialogs consistent.
final class PortalRadius {
  const PortalRadius._();

  static const double none = 0;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double full = 999;
}
