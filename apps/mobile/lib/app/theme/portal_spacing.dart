/// Defines the spacing scale used throughout Portal App.
///
/// Widgets should use these tokens instead of introducing arbitrary spacing
/// values. This keeps layouts consistent and easier to maintain.
final class PortalSpacing {
  const PortalSpacing._();

  static const double none = 0;
  static const double xxs = 2;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 40;
  static const double xxxl = 48;
}
